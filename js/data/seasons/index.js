/**
 * 年景（season）—— 一个"年份 + 市场风格 + 三只股票 + 六条新闻"的完整单元
 *
 * ============================================================
 * 为什么要有这一层
 * ============================================================
 *
 * 需求原话（第四版）：
 *   「不要告诉玩家在哪一年哪一个主题，让玩家自己把握。」
 *   「拓展市场，加入小牛、小熊、平静震荡等多种类型，
 *     每种类型可以有多个选择，暂定拓展到 20 年，
 *     每年三个股票，每个股票 6 种新闻，文件结构也处理下。」
 *
 * 于是数据层从"全局共享一个大池子"升级为**年景单元**：
 *
 *   STOCK_POOL（34 只虚构股）──┐
 *   NEWS_POOL（10 个行业新闻）─┴─→ SEASONS[20]（每年景 3 股 + 6 新闻）
 *                                       ↓
 *                                 关卡（5 关）× 每局抽 5 个不同年景
 *
 * ============================================================
 * ★ 两条不可破坏的契约
 * ============================================================
 *
 * 1. **年景的 id 与 style 只用于内部**，绝不直接展示给玩家。
 *    UI 上只说"第 N 关 / 本局市场"，让玩家自己从盘面判断牛熊。
 *    （早期版本在菜单上印"1996 · 全民炒股"，等于把答案先给了玩家。）
 *
 * 2. **每个年景的 3 只股票必须来自 3 个不同行业**。
 *    这是"分散持仓"教学的前提，也是新闻匹配机制的前提
 *    （新闻按 sector 命中，同行业重复会放大单一板块的影响）。
 *    由 validateData() 与 tools/diag-seasons.mjs 双重把关。
 *    注意有些行业只有 2 只股票（农业/传媒），不能在同一局里放两只。
 *
 * ============================================================
 * 数据结构
 * ============================================================
 *
 * 一个年景 = {
 *   id:      'y01'            // 内部编号（不展示）
 *   style:   'bull'           // 市场风格 → 决定价格路径中枢与爆雷率
 *   label:   '全民入场'        // 内部叙事主题（**不展示给玩家**）
 *   codes:   ['900101', ...]  // 恰好 3 只，行业互不重复
 *   news:    ['nl_01', ...]   // 恰好 6 条，来自 NEWS_POOL
 *   intro:   '…'              // 只在"关卡开始前的氛围提示"里可用（不说年份）
 * }
 *
 * ⚠️ news 里的 id 必须真实存在于 NEWS_POOL，且**同一只股票的行业
 *    至少要有一条新闻**，否则玩家会遇到"整局没有任何有效消息"。
 */

import { NEWS_POOL_MAP } from '../newspool';
import { POOL_MAP } from '../pool';

/**
 * 构造并校验一个年景
 *
 * 这里做**构造期校验**而不只是留给 validateData：年景数据是手写的，
 * 手写数据最容易出的错就是"代码打错一位"或"新闻 id 拼错"，
 * 那种错误在运行时表现成"某只股票整局没有新闻"——极难排查。
 * 在模块加载时就抛错，问题会立刻暴露在启动阶段。
 */
function season(id, style, label, codes, news, intro) {
  if (!id || !style || !label) throw new Error(`年景字段缺失: ${id}`);
  if (!Array.isArray(codes) || codes.length !== 3) {
    throw new Error(`年景 ${id} 必须恰好 3 只股票，实际 ${codes && codes.length}`);
  }
  if (!Array.isArray(news) || news.length !== 6) {
    throw new Error(`年景 ${id} 必须恰好 6 条新闻，实际 ${news && news.length}`);
  }

  // 股票必须存在
  const defs = codes.map((c) => {
    const s = POOL_MAP[c];
    if (!s) throw new Error(`年景 ${id} 引用了不存在的股票代码: ${c}`);
    return s;
  });

  // 行业必须互不重复
  const sectors = defs.map((s) => s.sector);
  if (new Set(sectors).size !== sectors.length) {
    throw new Error(`年景 ${id} 的股票行业重复: ${sectors.join('/')}`);
  }

  // 新闻必须存在且 id 不重复
  const ns = news.map((nid) => {
    const n = NEWS_POOL_MAP[nid];
    if (!n) throw new Error(`年景 ${id} 引用了不存在的新闻 id: ${nid}`);
    return n;
  });
  if (new Set(news).size !== news.length) {
    throw new Error(`年景 ${id} 的新闻 id 重复`);
  }

  // ★ 每只股票至少能被一条新闻"命中"（sector 相同）或该新闻是 macro
  defs.forEach((d) => {
    const hit = ns.some((n) => n.sector === 'macro' || n.sector === d.sector);
    if (!hit) {
      throw new Error(
        `年景 ${id} 的股票 ${d.name}(${d.sector}) 没有任何相关新闻 —— 该股整局将无消息驱动`,
      );
    }
  });

  return { id, style, label, codes, news, intro };
}

