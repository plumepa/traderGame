export const SEASON_MAP = SEASONS.reduce((acc, s) => {
  acc[s.id] = s;
  return acc;
}, {});

/**
 * 按市场风格取年景
 * @param {string} style 风格 key
 * @returns {Array} 该风格下的所有年景
 */
export function seasonsOfStyle(style) {
  return SEASONS.filter((s) => s.style === style);
}

/**
 * 按风格统计年景数量（调试/测试用）
 */
export function seasonCountByStyle() {
  const out = {};
  SEASONS.forEach((s) => { out[s.style] = (out[s.style] || 0) + 1; });
  return out;
}

/**
 * 取某个年景的三只股票定义
 * @param {object|string} s 年景对象或 id
 * @returns {Array} 股票定义（来自 STOCK_POOL）
 */
export function stocksOfSeason(s) {
  const seasonObj = typeof s === 'string' ? SEASON_MAP[s] : s;
  if (!seasonObj) return [];
  return seasonObj.codes.map((c) => POOL_MAP[c]).filter(Boolean);
}

/**
 * 取某个年景的六条新闻
 * @param {object|string} s 年景对象或 id
 * @returns {Array} 新闻定义（来自 NEWS_POOL）
 */
export function newsOfSeason(s) {
  const seasonObj = typeof s === 'string' ? SEASON_MAP[s] : s;
  if (!seasonObj) return [];
  return seasonObj.news.map((id) => NEWS_POOL_MAP[id]).filter(Boolean);
}

export default SEASONS;
